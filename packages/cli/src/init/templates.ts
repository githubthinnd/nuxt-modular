export function starterPageStub(options: StarterOptions): string {
  const label = titleCase(options.id)
  if (!hasDb(options)) {
    return `<script setup lang="ts">
useHead({ title: '${label}' })
</script>

<template>
  <main>
    <h1>${label}</h1>
    <p>A page contributed by the ${options.id} extension.</p>
  </main>
</template>
`
  }
  return `<script setup lang="ts">
useHead({ title: '${label}' })
const { data } = await useFetch<{ items: { id: string; title: string }[] }>('/api/${options.id}/items')
</script>

<template>
  <main>
    <h1>${label}</h1>
    <ul v-if="data?.items.length">
      <li v-for="item in data.items" :key="item.id">{{ item.title }}</li>
    </ul>
    <p v-else>No items yet. Run the seeder or add rows to <code>${tableName(options.id)}</code>.</p>
  </main>
</template>
`
}

